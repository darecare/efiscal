function translateValue(value, path = '') {
  if (typeof value === 'string') {
    if (path === 'createFiscalBill.buyerIdTypes' || path.startsWith('createFiscalBill.buyerIdTypes.')) {
      const key = path.split('.').pop()
      if (key && BUYER_ID_TYPES_SR[key]) return BUYER_ID_TYPES_SR[key]
    }
    return T[value] ?? value
  }
  if (Array.isArray(value)) {
    return value.map((v, i) => translateValue(v, `${path}[${i}]`))
  }
  if (value && typeof value === 'object') {
    const out = {}
    for (const [k, v] of Object.entries(value)) {
      const childPath = path ? `${path}.${k}` : k
      if (childPath === 'createFiscalBill.buyerIdTypes') {
        out[k] = { ...BUYER_ID_TYPES_SR }
        continue
      }
      out[k] = translateValue(v, childPath)
    }
    return out
  }
  return value
}

