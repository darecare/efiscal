const missing = []
function findMissing(obj, path = '') {
  if (typeof obj === 'string') {
    const enVal = path.split('.').reduce((o, k) => o?.[k], en)
    if (enVal && obj === enVal && !path.includes('buyerIdTypes') && enVal.length > 1 && !/^[0-9 –\-]/.test(enVal) && enVal !== 'eFiscal' && enVal !== 'SKU' && enVal !== 'GTIN' && enVal !== 'PAC' && enVal !== 'Email' && enVal !== 'MerchantPro' && enVal !== 'WooCommerce' && enVal !== 'Shopify') {
      missing.push({ path, en: enVal })
    }
    return
  }
  if (obj && typeof obj === 'object') {
    for (const [k, v] of Object.entries(obj)) {
      findMissing(v, path ? `${path}.${k}` : k)
    }
  }
}
